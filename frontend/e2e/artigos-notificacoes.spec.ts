import {test,expect,Page} from "@playwright/test";
async function login(page:Page,route:string,user="admin"){
  await page.goto(`/login?next=${encodeURIComponent(route)}`);
  await page.locator('input[autocomplete="email"]').first().fill(`${user}@example.test`);
  await page.locator('input[autocomplete="current-password"]').fill("E2e-only!Password-482");
  await page.getByRole("button",{name:"Entrar",exact:true}).first().click();
  await expect(page).toHaveURL(url=>url.pathname===route);
}

test("articles standard previews unsaved changes, schedules, clears schedule and publishes",async({page})=>{
  const errors:string[]=[];page.on("pageerror",error=>errors.push(error.message));
  await login(page,"/admin/artigos");
  await page.getByRole("button",{name:"Novo artigo",exact:true}).first().click();
  const editor=page.getByRole("dialog").filter({has:page.getByRole("heading",{name:"Novo artigo",exact:true})});
  await editor.getByLabel("Título *",{exact:true}).fill("Artigo inicial E2E");
  await editor.locator('[contenteditable="true"]').fill("Conteúdo atualizado da plataforma");
  await editor.getByLabel("Título *",{exact:true}).fill("Artigo revisão E2E");
  await editor.getByRole("button",{name:"Prévia das alterações"}).click();
  const preview=page.getByRole("dialog").filter({has:page.getByRole("heading",{name:"Prévia do artigo",exact:true})});
  await expect(preview.getByRole("heading",{name:"Artigo revisão E2E",exact:true})).toBeVisible();
  await expect(preview.getByText("Conteúdo atualizado da plataforma",{exact:true})).toBeVisible();
  await preview.getByRole("button",{name:"Close",exact:true}).click();
  const date=new Date(Date.now()+2*86400000);const local=new Date(date.getTime()-date.getTimezoneOffset()*60000).toISOString().slice(0,16);
  await editor.getByLabel("Publicação agendada (horário local)",{exact:true}).fill(local);
  await editor.getByRole("button",{name:"Salvar artigo",exact:true}).click();await expect(editor).toBeHidden();
  await expect(page.getByRole("table").getByText("Agendado",{exact:true})).toBeVisible();
  await page.getByLabel("Buscar artigos",{exact:true}).fill("Artigo revisão E2E");await expect(page).toHaveURL(/search=/);
  await page.reload();await expect(page.getByLabel("Buscar artigos",{exact:true})).toHaveValue("Artigo revisão E2E");
  await page.getByRole("button",{name:"Editar artigo Artigo revisão E2E",exact:true}).click();
  const edit=page.getByRole("dialog");
  await expect(edit.getByLabel("Publicação agendada (horário local)",{exact:true})).toHaveValue(local);
  await edit.getByLabel("Publicação agendada (horário local)",{exact:true}).fill("");
  await edit.getByRole("button",{name:"Salvar artigo"}).click();await expect(edit).toBeHidden();
  await expect(page.getByRole("table").getByText("Rascunho",{exact:true})).toBeVisible();
  await page.getByRole("table").getByRole("button",{name:"Publicar",exact:true}).click();
  await page.getByRole("dialog").getByRole("button",{name:"Confirmar",exact:true}).click();
  await expect(page.getByRole("table").getByText("Publicado",{exact:true})).toBeVisible();
  await page.getByRole("button",{name:"Duplicar artigo Artigo revisão E2E",exact:true}).click();
  await expect(page.getByRole("status").filter({hasText:"2 registros encontrados"})).toBeVisible();
  await page.screenshot({path:"/tmp/admin-artigos-desktop.png",fullPage:true});
  await page.setViewportSize({width:390,height:844});await page.reload();
  await expect(page.getByRole("table").getByText("Artigo revisão E2E",{exact:true})).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
  await page.screenshot({path:"/tmp/admin-artigos-mobile.png",fullPage:true});expect(errors).toEqual([]);
});

