import {test,expect} from '@playwright/test';

test('create a shared text, link an existing question and expand during resolution',async({page})=>{
 const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
 await page.goto('/login?next=/admin/textos-apoio');
 await page.locator('input[autocomplete="email"]').first().fill('admin@example.test');
 await page.locator('input[autocomplete="current-password"]').fill('E2e-only!Password-482');
 await page.getByRole('button',{name:'Entrar',exact:true}).first().click();
 await expect(page).toHaveURL(url=>url.pathname==='/admin/textos-apoio');
 await page.getByRole('button',{name:'Novo texto',exact:true}).click();
 let dialog=page.getByRole('dialog');
 await dialog.getByLabel('Título',{exact:true}).fill('Crônica para interpretação E2E');
 await dialog.getByRole('textbox').nth(1).fill('Os candidatos estudam juntos. A leitura abre caminhos.');
 await dialog.getByLabel('Referência / autoria (opcional)').fill('Texto sintético de teste');
 await dialog.getByRole('button',{name:'Salvar texto',exact:true}).click();
 await expect(dialog).toBeHidden();
 await expect(page.getByRole('table').getByText('Crônica para interpretação E2E',{exact:false})).toBeVisible();
 await page.goto('/admin/questoes');
 await page.getByRole('table').getByRole('button',{name:'Texto de apoio',exact:true}).first().click();
 dialog=page.getByRole('dialog');
 await dialog.getByLabel('Pesquisar texto',{exact:true}).fill('Crônica');
 await expect(dialog.locator('select option').filter({hasText:'Crônica para interpretação E2E'})).toHaveCount(1);
 await dialog.getByLabel('Texto de apoio vinculado').selectOption({label:'#1 · Crônica para interpretação E2E'});
 await dialog.getByRole('button',{name:'Salvar vínculo',exact:true}).click();
 await expect(dialog).toBeHidden();
 await page.goto('/questions');
 const panel=page.locator('details').filter({hasText:'Crônica para interpretação E2E'});
 await expect(panel).toBeVisible();
 await expect(panel).not.toHaveAttribute('open','');
 await panel.locator('summary').click();
 await expect(panel.getByText('Os candidatos estudam juntos. A leitura abre caminhos.',{exact:true})).toBeVisible();
 await panel.locator('summary').focus();await page.keyboard.press('Enter');
 await expect(panel).not.toHaveAttribute('open','');
 await page.setViewportSize({width:390,height:844});
 await panel.locator('summary').click();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
 await page.screenshot({path:'/tmp/support-text-mobile.png',fullPage:true});
 await page.goto('/admin/textos-apoio');
 await expect(page.getByRole('button',{name:'Excluir',exact:true})).toBeDisabled();
 expect(errors).toEqual([]);
});
